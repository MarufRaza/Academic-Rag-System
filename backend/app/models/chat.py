from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class ChatMessage(BaseModel):
    role: Literal["user", "assistant", "system"] = Field(..., description="Role of the sender")
    content: str = Field(..., description="Text content of the message")


class ChatRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Question asked by the student")
    chat_history: Optional[List[ChatMessage]] = Field(default=[], description="Previous conversation turns for context condensation")


class SourceCitation(BaseModel):
    document: str = Field(..., description="Filename of the cited document")
    page: int = Field(..., description="1-indexed page number in the original document")
    chunk_index: int = Field(..., description="Zero-indexed chunk identifier within the document")
    content: str = Field(..., description="Excerpt or snippet from the page that supports the answer")
    score: Optional[float] = Field(default=None, description="Relevance score from similarity search")


class ChatResponse(BaseModel):
    answer: str = Field(..., description="Grounded answer generated by the assistant")
    sources: List[SourceCitation] = Field(default=[], description="List of source citations used")
    standalone_question: Optional[str] = Field(default=None, description="Condensed question after history analysis")
